#!/usr/bin/env bash
# Regenerates generated/fallback_shaders.h: the shaders d3d12_xs substitutes
# when a console shader has no translation (REBOX_SHADER_FALLBACK).
# Needs vkd3d-compiler and dxc (both in `nix develop`). The output is committed so
# ordinary builds don't need the compiler.
set -euo pipefail
cd "$(dirname "$0")/.."
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

# Draws nothing: every vertex is outside the clip volume (x > w), so every
# primitive is trivially rejected without any w = 0 edge cases.
printf 'float4 main() : SV_Position { return float4(2, 2, 2, 1); }\n' > "$work/vs.hlsl"
# Never reached through the VS above; magenta if a real VS feeds it.
printf 'float4 main() : SV_Target { return float4(1, 0, 1, 1); }\n' > "$work/ps.hlsl"
# Does nothing.
printf '[numthreads(1, 1, 1)] void main() {}\n' > "$work/cs.hlsl"
cat > "$work/ms.hlsl" <<'HLSL'
struct vertex { float4 position : SV_Position; };
[outputtopology("triangle")] [numthreads(1, 1, 1)]
void main(uint tid : SV_GroupThreadID, out vertices vertex verts[1], out indices uint3 tris[1])
{
    SetMeshOutputCounts(0, 0);
    /* Never runs (one thread); the validator wants every output written. */
    if (tid > 0)
    {
        verts[0].position = float4(0, 0, 0, 0);
        tris[0] = uint3(0, 0, 0);
    }
}
HLSL
cat > "$work/as.hlsl" <<'HLSL'
struct payload_t { uint unused; };
groupshared payload_t payload;
[numthreads(1, 1, 1)] void main() { DispatchMesh(0, 0, 0, payload); }
HLSL

{
    echo "/* Generated by tools/gen_fallback_shaders.sh; do not edit. SM5 DXBC. */"
    echo "#pragma once"
    for s in vs ps cs; do
        vkd3d-compiler -x hlsl -b dxbc-tpf -p ${s}_5_0 -o "$work/$s.dxbc" "$work/$s.hlsl"
        echo "static const unsigned char fallback_${s}[] = {"
        od -An -v -tx1 "$work/$s.dxbc" | sed 's/ \([0-9a-f][0-9a-f]\)/0x\1, /g; s/^/   /'
        echo "};"
    done
    # Mesh pipelines: SM 6.5 DXIL from dxc (unsigned; vkd3d-proton doesn't
    # check). The MS emits no primitives, the AS launches no mesh groups.
    for s in ms as; do
        dxc -nologo -T ${s}_6_5 -E main -Fo "$work/$s.dxil" "$work/$s.hlsl" >/dev/null
        echo "static const unsigned char fallback_${s}[] = {"
        od -An -v -tx1 "$work/$s.dxil" | sed 's/ \([0-9a-f][0-9a-f]\)/0x\1, /g; s/^/   /'
        echo "};"
    done
} > generated/fallback_shaders.h
echo "wrote generated/fallback_shaders.h"

# Bilinear scale for ReboxBlit (the FidelityFX stub's upscaler): samples
# the src_extent part of t0 and writes all of u0's dst_size.
cat > "$work/blit.hlsl" <<'HLSL'
Texture2D<float4> src : register(t0);
RWTexture2D<float4> dst : register(u0);
SamplerState linear_clamp : register(s0);
cbuffer constants : register(b0)
{
    float2 inv_dst_size;
    float2 src_uv_scale;
    uint2 dst_size;
};
[numthreads(8, 8, 1)]
void main(uint3 id : SV_DispatchThreadID)
{
    if (any(id.xy >= dst_size))
        return;
    float2 uv = (float2(id.xy) + 0.5) * inv_dst_size * src_uv_scale;
    dst[id.xy] = src.SampleLevel(linear_clamp, uv, 0);
}
HLSL
vkd3d-compiler -x hlsl -b dxbc-tpf -p cs_5_0 -o "$work/blit.dxbc" "$work/blit.hlsl"

# REBOX_DEBUG_VIEW (shims/d3d12_xs/debug_view.c): one of the title's render targets or depth
# buffers shown in place of the presented plane. Point-samples t0 (Load: any float format, depth
# included, no filtering) into all of u0. Modes: 0 colour, 1 colour with an HDR roll-off, 2 depth
# with the far plane at 0 (reversed Z), 3 depth with the far plane at 1. Depth is shown on a log
# scale over `power` decades from the near plane; a cleared texel (exactly the far value) is dark
# blue, so geometry stands out from what nothing was drawn over.
cat > "$work/debug_view.hlsl" <<'HLSL'
Texture2D<float4> src : register(t0);
RWTexture2D<float4> dst : register(u0);
cbuffer constants : register(b0)
{
    uint2 dst_size;
    uint2 src_size;
    uint mode;
    float scale;
    float power;
    uint swizzle;
};
[numthreads(8, 8, 1)]
void main(uint3 id : SV_DispatchThreadID)
{
    if (any(id.xy >= dst_size))
        return;
    uint2 at = min(uint2(float2(id.xy) * float2(src_size) / float2(dst_size)), src_size - 1);
    float4 v = src.Load(int3(at, 0));
    if (swizzle == 1) v = v.rrrr;
    else if (swizzle == 2) v = v.gggg;
    else if (swizzle == 3) v = v.bbbb;
    else if (swizzle == 4) v = v.aaaa;
    float3 c;
    if (mode >= 2)
    {
        float d = mode == 2 ? v.r : 1.0 - v.r;
        if (d <= 0.0)
            c = float3(0.0, 0.0, 0.3);
        else
            c = saturate(1.0 + log10(min(d, 1.0)) / power).xxx;
    }
    else
    {
        c = max(v.rgb * scale, 0.0);
        if (mode == 1)
            c = c / (1.0 + c);
    }
    dst[id.xy] = float4(saturate(c), 1.0);
}
HLSL
vkd3d-compiler -x hlsl -b dxbc-tpf -p cs_5_0 -o "$work/debug_view.dxbc" "$work/debug_view.hlsl"
{
    echo "/* Generated by tools/gen_fallback_shaders.sh; do not edit. SM5 DXBC. */"
    echo "#pragma once"
    echo "static const unsigned char blit_cs[] = {"
    od -An -v -tx1 "$work/blit.dxbc" | sed 's/ \([0-9a-f][0-9a-f]\)/0x\1, /g; s/^/   /'
    echo "};"
    echo "static const unsigned char debug_view_cs[] = {"
    od -An -v -tx1 "$work/debug_view.dxbc" | sed 's/ \([0-9a-f][0-9a-f]\)/0x\1, /g; s/^/   /'
    echo "};"
} > generated/blit_shaders.h
echo "wrote generated/blit_shaders.h"

# Smoke-test shader (tests/smoke.c): writes a constant through a UAV that
# comes from a descriptor table, so a mistranslated table handle shows.
printf 'RWByteAddressBuffer o : register(u0);\n[numthreads(1, 1, 1)] void main() { o.Store(0, 0x5ca71e77); }\n' > "$work/uav.hlsl"
printf '[numthreads(1, 1, 1)] void main() {}\n' > "$work/empty.hlsl"
vkd3d-compiler -x hlsl -b dxbc-tpf -p cs_5_0 -o "$work/uav.dxbc" "$work/uav.hlsl"
vkd3d-compiler -x hlsl -b dxbc-tpf -p cs_5_0 -o "$work/empty.dxbc" "$work/empty.hlsl"
{
    echo "/* Generated by tools/gen_fallback_shaders.sh; do not edit. SM5 DXBC. */"
    echo "#pragma once"
    echo "static const unsigned char test_uav_write_cs[] = {"
    od -An -v -tx1 "$work/uav.dxbc" | sed 's/ \([0-9a-f][0-9a-f]\)/0x\1, /g; s/^/   /'
    echo "};"
} > generated/test_shaders.h
echo "wrote generated/test_shaders.h"

# Smoke-test console shaders (vkd3d-proton patch 0002): SPIR-V under the
# "SCSV" header d3d12_xs passes to the patched vkd3d-proton (docs/shaders.md).
# The compute shader writes its 32 user SGPRs and a marker to the address in
# s0:s1 (root parameter 0, a root UAV); the pixel shader does the same 64
# dwords further on. The VS draws a fullscreen triangle. Graphics stages embed
# a DXBC with matching I/O signatures, as a console container would.
cat > "$work/console.comp" <<'GLSL'
#version 460
#extension GL_EXT_buffer_reference : require
#extension GL_EXT_buffer_reference_uvec2 : require
layout(local_size_x = 1) in;
layout(buffer_reference, std430, buffer_reference_align = 4) buffer Out { uint v[]; };
layout(push_constant, std430) uniform Sgprs { uint s[32]; uvec2 heap_base; uvec2 code_base; } pc;
void main()
{
    if (pc.s[0] == 0u && pc.s[1] == 0u)
        return;
    Out o = Out(uvec2(pc.s[0], pc.s[1]));
    for (int i = 0; i < 32; i++)
        o.v[i] = pc.s[i];
    o.v[32] = 0x5ca7c0deu;
}
GLSL
cat > "$work/console.vert" <<'GLSL'
#version 460
void main()
{
    vec2 p = vec2((gl_VertexIndex << 1) & 2, gl_VertexIndex & 2);
    gl_Position = vec4(p * 2.0 - 1.0, 0.0, 1.0);
}
GLSL
cat > "$work/console.frag" <<'GLSL'
#version 460
#extension GL_EXT_buffer_reference : require
#extension GL_EXT_buffer_reference_uvec2 : require
layout(buffer_reference, std430, buffer_reference_align = 4) buffer Out { uint v[]; };
layout(push_constant, std430) uniform Sgprs { uint s[32]; uvec2 heap_base; uvec2 code_base; } pc;
layout(location = 0) out vec4 color;
void main()
{
    color = vec4(1.0);
    if (pc.s[0] == 0u && pc.s[1] == 0u)
        return;
    Out o = Out(uvec2(pc.s[0], pc.s[1]));
    for (int i = 0; i < 32; i++)
        o.v[64 + i] = pc.s[i];
    o.v[96] = 0x5ca7f4a9u;
}
GLSL
# Descriptor lookup (patch 4): reads the raw descriptor at the table address
# in s6:s7, finds it in the bound resource heap's lookup table (push dwords
# 36-37), and writes the heap index and probe count at dword s2 of the root
# UAV (0xfffffffe: no table address or lookup table; 0xffffffff: miss).
cat > "$work/console.lookup" <<'GLSL'
#version 460
#extension GL_EXT_buffer_reference : require
#extension GL_EXT_buffer_reference_uvec2 : require
layout(local_size_x = 1) in;
layout(buffer_reference, std430, buffer_reference_align = 4) buffer Words { uint v[]; };
layout(push_constant, std430) uniform Sgprs
{
    uint s[32];
    uvec2 heap_base, code_base, resource_lookup, sampler_lookup;
} pc;
void main()
{
    if (pc.s[0] == 0u && pc.s[1] == 0u)
        return;
    Words o = Words(uvec2(pc.s[0], pc.s[1]));
    uint at = pc.s[2];
    if ((pc.s[6] | pc.s[7]) == 0u || (pc.resource_lookup.x | pc.resource_lookup.y) == 0u)
    {
        o.v[at] = 0xfffffffeu;
        return;
    }
    Words d = Words(uvec2(pc.s[6], pc.s[7]));
    Words t = Words(pc.resource_lookup);
    uint key[8], h = 2166136261u;
    for (int i = 0; i < 8; i++)
    {
        key[i] = d.v[i];
        h = (h ^ key[i]) * 16777619u;
    }
    for (uint p = 0u; p < 8u; p++)
    {
        uint e = 1u + ((h + p) & t.v[0]) * 10u;
        bool same = true;
        for (int i = 0; i < 8; i++)
            same = same && t.v[e + i] == key[i];
        if (same)
        {
            o.v[at] = t.v[e + 8u];
            o.v[at + 1u] = p;
            return;
        }
        if (t.v[e + 8u] == 0xffffffffu)
            break;
    }
    o.v[at] = 0xffffffffu;
}
GLSL
printf 'float4 main(uint id : SV_VertexID) : SV_Position { return 0; }\n' > "$work/sig_vs.hlsl"
printf 'float4 main(float4 p : SV_Position) : SV_Target { return 0; }\n' > "$work/sig_ps.hlsl"
vkd3d-compiler -x hlsl -b dxbc-tpf -p vs_5_0 -o "$work/sig_vs.dxbc" "$work/sig_vs.hlsl"
vkd3d-compiler -x hlsl -b dxbc-tpf -p ps_5_0 -o "$work/sig_ps.dxbc" "$work/sig_ps.hlsl"
for s in comp vert frag lookup; do
    glslangValidator -V --target-env vulkan1.2 -S $( [ $s = lookup ] && echo comp || echo $s ) \
        -o "$work/console_$s.spv" "$work/console.$s" >/dev/null
done
# Header (44 bytes): magic "SCSV", version 1, Vulkan stage bit, wave size (0:
# driver's choice), workgroup size, SPIR-V offset and size, DXBC offset and size.
python3 - "$work" <<'PY'
import struct, sys
w = sys.argv[1]
def scsv(stage, spv, dxbc=None, wg=(0, 0, 0)):
    spv = open(f'{w}/{spv}', 'rb').read()
    dx = open(f'{w}/{dxbc}', 'rb').read() if dxbc else b''
    hdr = struct.pack('<4s10I', b'SCSV', 1, stage, 0, *wg, 44, len(spv), 44 + len(spv) if dx else 0, len(dx))
    return hdr + spv + dx
for name, blob in (('comp', scsv(0x20, 'console_comp.spv', wg=(1, 1, 1))),
                   ('vert', scsv(0x01, 'console_vert.spv', 'sig_vs.dxbc')),
                   ('frag', scsv(0x10, 'console_frag.spv', 'sig_ps.dxbc')),
                   ('lookup', scsv(0x20, 'console_lookup.spv', wg=(1, 1, 1)))):
    open(f'{w}/console_{name}.scsv', 'wb').write(blob)
PY
{
    echo "/* Generated by tools/gen_fallback_shaders.sh; do not edit. SM5 DXBC, and SPIR-V under SCSV headers. */"
    echo "#pragma once"
    echo "static const unsigned char test_uav_write_cs[] = {"
    od -An -v -tx1 "$work/uav.dxbc" | sed 's/ \([0-9a-f][0-9a-f]\)/0x\1, /g; s/^/   /'
    echo "};"
    echo "static const unsigned char test_empty_cs[] = {"
    od -An -v -tx1 "$work/empty.dxbc" | sed 's/ \([0-9a-f][0-9a-f]\)/0x\1, /g; s/^/   /'
    echo "};"
    for s in comp vert frag lookup; do
        echo "static const unsigned char test_console_${s}[] = {"
        od -An -v -tx1 "$work/console_$s.scsv" | sed 's/ \([0-9a-f][0-9a-f]\)/0x\1, /g; s/^/   /'
        echo "};"
    done
} > generated/test_shaders.h
echo "wrote generated/test_shaders.h (with the console shaders)"

# REBOX_STANDIN_PIXEL (shims/d3d12_xs/console_compile.c): the pixel stage a console mesh draw gets
# while its own is still compiling, or failed: every colour output a grey that darkens with distance
# (depth's far plane at 0, as the title's), so the meshes' shapes show in the G-buffer at once.
cat > "$work/standin.frag" <<'GLSL'
#version 450
layout(location = 0) out vec4 o0;
layout(location = 1) out vec4 o1;
layout(location = 2) out vec4 o2;
layout(location = 3) out vec4 o3;
layout(location = 4) out vec4 o4;
layout(location = 5) out vec4 o5;
layout(location = 6) out vec4 o6;
layout(location = 7) out vec4 o7;
void main()
{
    /* Four decades of depth from the near plane, on a log scale. */
    float g = 0.25 + 0.65 * clamp(1.0 + log2(max(gl_FragCoord.z, 1e-6)) * 0.0752575, 0.0, 1.0);
    vec4 c = vec4(g, g, g, 1.0);
    o0 = c; o1 = c; o2 = c; o3 = c; o4 = c; o5 = c; o6 = c; o7 = c;
}
GLSL
glslangValidator -V --target-env vulkan1.2 -S frag -o "$work/standin.spv" "$work/standin.frag" >/dev/null
{
    echo "/* Generated by tools/gen_fallback_shaders.sh; do not edit. SPIR-V words. */"
    echo "#pragma once"
    echo "static const unsigned int standin_pixel_spirv[] = {"
    od -An -v -tx4 "$work/standin.spv" | sed 's/ \([0-9a-f]\{8\}\)/0x\1, /g; s/^/   /'
    echo "};"
} > generated/standin_shaders.h
echo "wrote generated/standin_shaders.h"
